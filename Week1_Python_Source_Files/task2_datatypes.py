"""
Task 2: Variables & Data Types
--------------------------------
This program declares variables of different data types (int, float, string,
boolean) and prints each variable along with its data type using type().
"""

# Declaring variables of different data types
age = 21                      # Integer
height = 5.9                  # Float
student_name = "Aarav Sharma" # String
is_enrolled = True            # Boolean

# Printing variables with their data types
print("Value:", age, "\tData Type:", type(age))
print("Value:", height, "\tData Type:", type(height))
print("Value:", student_name, "\tData Type:", type(student_name))
print("Value:", is_enrolled, "\tData Type:", type(is_enrolled))
